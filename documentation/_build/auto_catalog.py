"""Scan NewsMindAI V2 source to append an accurate file catalog to the guide."""

from __future__ import annotations

import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # NewsMindAI V2

SKIP_DIRS = {
    ".git",
    "__pycache__",
    ".pytest_cache",
    ".venv",
    "venv",
    "node_modules",
    "documentation",
}


def iter_py_files() -> list[Path]:
    files: list[Path] = []
    for path in ROOT.rglob("*.py"):
        if any(part in SKIP_DIRS for part in path.parts):
            continue
        if path.name.startswith("_probe"):
            continue
        files.append(path)
    return sorted(files)


def summarize_py(path: Path) -> dict:
    rel = path.relative_to(ROOT).as_posix()
    text = path.read_text(encoding="utf-8", errors="replace")
    doc = ""
    classes: list[str] = []
    functions: list[str] = []
    try:
        tree = ast.parse(text)
        doc = ast.get_docstring(tree) or ""
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                classes.append(node.name)
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if not node.name.startswith("_"):
                    functions.append(node.name)
    except SyntaxError:
        doc = "(unparseable)"
    return {
        "path": rel,
        "lines": text.count("\n") + 1,
        "doc": " ".join(doc.split())[:220],
        "classes": classes[:20],
        "functions": functions[:30],
    }


def extract_routes() -> list[tuple[str, str, str]]:
    """Return (methods, path, file) from APIRouter decorators."""
    routes: list[tuple[str, str, str]] = []
    routers = ROOT / "api" / "routers"
    prefix_re = re.compile(r'APIRouter\(\s*prefix\s*=\s*["\']([^"\']+)["\']')
    deco_re = re.compile(
        r'@router\.(get|post|put|delete|patch)\(\s*["\']([^"\']*)["\']',
        re.IGNORECASE,
    )
    for path in sorted(routers.glob("*.py")):
        if path.name == "__init__.py":
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        m = prefix_re.search(text)
        prefix = m.group(1) if m else ""
        for dm in deco_re.finditer(text):
            method = dm.group(1).upper()
            sub = dm.group(2)
            full = (prefix + sub) if sub.startswith("/") or not sub else f"{prefix}/{sub}"
            if not sub:
                full = prefix or "/"
            routes.append((method, full, path.relative_to(ROOT).as_posix()))
    # static easy route
    routes.append(("GET", "/easy", "api/main.py"))
    return routes


def add_catalog_chapter(doc, helpers) -> None:
    h = helpers.h
    p = helpers.p
    bullet = helpers.bullet
    table = helpers.table
    note = helpers.note

    h(doc, "Appendix D — Auto-Generated Source Catalog", 1)
    p(
        doc,
        "This appendix was generated by scanning the repository at documentation build time. "
        "It lists every .py file under NewsMindAI V2 (excluding caches, venvs, probes, and this "
        "documentation folder) with line counts, docstring summary, classes, and public functions.",
    )

    files = [summarize_py(p_) for p_ in iter_py_files()]
    p(doc, f"Python source files catalogued: {len(files)}")

    # Group by top-level package
    groups: dict[str, list[dict]] = {}
    for item in files:
        top = item["path"].split("/", 1)[0]
        groups.setdefault(top, []).append(item)

    for top in sorted(groups):
        h(doc, f"D.{top}", 2)
        for item in groups[top]:
            h(doc, item["path"], 3)
            p(doc, f"Lines: {item['lines']}")
            if item["doc"]:
                p(doc, f"Docstring: {item['doc']}")
            if item["classes"]:
                bullet(doc, "Classes: " + ", ".join(item["classes"]))
            if item["functions"]:
                bullet(doc, "Public functions: " + ", ".join(item["functions"]))

    h(doc, "Appendix E — Auto-Extracted HTTP Routes", 1)
    note(doc, "Extracted from @router.* decorators plus GET /easy. Path params appear as in source.")
    rows = []
    for method, path, file in extract_routes():
        rows.append([method, path, file])
    # Word tables get huge; chunk
    chunk = 25
    for i in range(0, len(rows), chunk):
        table(doc, ["Method", "Path", "File"], rows[i : i + chunk])
    p(doc, f"Total extracted routes: {len(rows)}")
